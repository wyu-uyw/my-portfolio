  for select to anon, authenticated using (true);

-- ---------- 관리자 (관리 페이지 로그인) ----------
-- 관리자 = admin_users 표에 user_id가 있는 Supabase Auth 계정. 등록 방법은 이 파일 맨 아래 "관리자 등록".
-- admin_users 표 자체는 정책이 없어 사이트에서 읽거나 쓸 수 없고, is_admin() 함수로만 확인한다.
create table if not exists public.admin_users (
  user_id     uuid primary key references auth.users(id) on delete cascade,
  created_at  timestamptz not null default now()
);
alter table public.admin_users enable row level security;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $
  select exists (select 1 from public.admin_users where user_id = auth.uid());
$;
grant execute on function public.is_admin() to anon, authenticated;

-- 관리자는 모든 표를 읽고(비공개 포함) 쓸 수 있다
do $
declare t text;
begin
  foreach t in array array['collections', 'works', 'journal_posts', 'cv_items', 'site_settings', 'inquiries'] loop
    execute format('drop policy if exists "admin all %1$s" on public.%1$I', t);
    execute format('create policy "admin all %1$s" on public.%1$I for all to authenticated using (public.is_admin()) with check (public.is_admin())', t);
  end loop;
end $;

drop policy if exists "public read collections" on public.collections;
create policy "public read collections" on public.collections
  for select to anon, authenticated using (is_public = true);

drop policy if exists "public read works" on public.works;
create policy "public read works" on public.works
  for select to anon, authenticated using (is_public = true);

drop policy if exists "public read journal_posts" on public.journal_posts;
create policy "public read journal_posts" on public.journal_posts
  for select to anon, authenticated using (is_public = true);

drop policy if exists "public read cv_items" on public.cv_items;
create policy "public read cv_items" on public.cv_items
  for select to anon, authenticated using (is_public = true);

-- 문의: 방문자(anon)는 insert만. 읽기·처리·삭제는 위의 관리자 정책으로만.
drop policy if exists "anon insert inquiries" on public.inquiries;
create policy "anon insert inquiries" on public.inquiries
  for insert to anon, authenticated with check (true);

-- ---------- Storage ----------
-- 이미지 버킷 `portfolio` (공개 읽기). 올리기·바꾸기·지우기는 관리자만 (관리 페이지 사진 업로드).
insert into storage.buckets (id, name, public)
values ('portfolio', 'portfolio', true)
on conflict (id) do update set public = true;

drop policy if exists "public read portfolio images" on storage.objects;
create policy "public read portfolio images" on storage.objects
  for select to anon, authenticated using (bucket_id = 'portfolio');

drop policy if exists "admin write portfolio images" on storage.objects;
create policy "admin write portfolio images" on storage.objects
  for insert to authenticated with check (bucket_id = 'portfolio' and public.is_admin());
drop policy if exists "admin update portfolio images" on storage.objects;
create policy "admin update portfolio images" on storage.objects
  for update to authenticated using (bucket_id = 'portfolio' and public.is_admin());
drop policy if exists "admin delete portfolio images" on storage.objects;
create policy "admin delete portfolio images" on storage.objects
  for delete to authenticated using (bucket_id = 'portfolio' and public.is_admin());

