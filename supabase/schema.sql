  sns              jsonb not null default '[]',   -- [{ "label": "Instagram", "href": "https://…" }]
  status           text not null default '',
  description      text not null default '',
  main_role        text not null default '',
  main_intro       text not null default '',
  about_photo      text,
  about_one_liner  text not null default '',
  about_bio        text not null default '',
  about_statement  text not null default '',      -- 빈 줄로 문단 구분
  cv_pdf           text,
  journal_lead     text not null default '',
  updated_at       timestamptz not null default now()
