insert into public.site_settings (id) values (1) on conflict (id) do nothing;

create table if not exists public.inquiries (
  id          bigint generated by default as identity primary key,
  name        text not null check (char_length(name) between 1 and 100),
  email       text not null check (char_length(email) between 3 and 200),
  type        text not null check (type in ('collab', 'commission', 'exhibition', 'etc')),
  message     text not null check (char_length(message) between 1 and 5000),
  status      text not null default 'new' check (status in ('new', 'done')),   -- 관리 페이지 문의함 처리 표시
  created_at  timestamptz not null default now()
);
alter table public.inquiries add column if not exists status text not null default 'new';

